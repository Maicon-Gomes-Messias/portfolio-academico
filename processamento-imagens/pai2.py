# Função para medir o ângulo de Cobb e determinar o tipo de escoliose
def measure_cobb_angle(image_path):
    # Carregar a imagem usando OpenCV
    image = cv2.imread(image_path, cv2.IMREAD_GRAYSCALE)

    # Detecção de bordas
    edges = cv2.Canny(image, 50, 150, apertureSize=3)

    # Detectar linhas usando Transformada de Hough
    lines = cv2.HoughLines(edges, 1, np.pi/180, 200)

    if lines is not None:
        lines = sorted(lines, key=lambda x: x[0][0])  # Corrigir acesso ao primeiro elemento
        if len(lines) >= 2:
            rho1, theta1 = lines[0][0]
            rho2, theta2 = lines[1][0]

            # Calcular ângulo entre as duas linhas
            angle1 = np.degrees(theta1)
            angle2 = np.degrees(theta2)
            cobb_angle = abs(angle1 - angle2)

            # Determinar o tipo de curvatura (simplificado para fins de exemplo)
            curvature_type = 'S' if cobb_angle > 20 else 'C'

            return cobb_angle, curvature_type

    return 0, 'N/A'  # Retornar 0 se não for possível calcular

# Função para processar e classificar a imagem
def classify_and_measure(image_path, model):
    # Carregar e transformar a imagem
    image = Image.open(image_path).convert('RGB')
    transform = transforms.Compose([
        transforms.Resize((224, 224)),
        transforms.ToTensor(),
    ])
    image_tensor = transform(image).unsqueeze(0)  # Adicionar dimensão do batch

    # Mover a imagem e o modelo para o dispositivo correto
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    image_tensor = image_tensor.to(device)
    model.to(device)

    # Classificar a imagem
    model.eval()
    with torch.no_grad():
        output = model(image_tensor)
        _, predicted = torch.max(output.data, 1)

    if predicted.item() == 0:
        return "Não há escoliose."
    else:
        # Medir o ângulo de Cobb se escoliose for detectada
        angle_of_cobb, curvature_type = measure_cobb_angle(image_path)

        result_message = f"Ângulo de Cobb: {angle_of_cobb:.2f} graus. Tipo de curvatura: {curvature_type}. "

        if angle_of_cobb < 10:
            return result_message + "Não é escoliose."
        elif angle_of_cobb < 25:
            return result_message + "Escoliose leve."
        elif angle_of_cobb < 45:
            return result_message + "Escoliose moderada."
        else:
            return result_message + "Escoliose grave."


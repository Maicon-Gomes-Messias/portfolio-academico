import os
import torch
import torch.nn as nn
import torch.optim as optim
from torch.utils.data import DataLoader, Dataset
import torchvision.transforms as transforms
from torchvision import models
from sklearn.model_selection import train_test_split
from PIL import Image

# Montar o Google Drive
from google.colab import drive
drive.mount('/content/drive')

# Caminhos das pastas (
normal_dir = '/content/drive/MyDrive/Projeto-Escoliose/Normal'
escoliose_dir = '/content/drive/MyDrive/Projeto-Escoliose/Escoliose'

# Carregar imagens e criar rótulos
normal_images = [os.path.join(normal_dir, img) for img in os.listdir(normal_dir) if img.endswith('.jpg')]
escoliose_images = [os.path.join(escoliose_dir, img) for img in os.listdir(escoliose_dir) if img.endswith('.jpg')]

images = normal_images + escoliose_images
labels = [0] * len(normal_images) + [1] * len(escoliose_images)  # 0: normal, 1: escoliose

# Dividir em treino e teste
train_images, test_images, train_labels, test_labels = train_test_split(images, labels, test_size=0.2, random_state=42)

# Definição da classe Dataset
class ScoliosisDataset(Dataset):
    def __init__(self, image_paths, labels, transform=None):
        self.image_paths = image_paths
        self.labels = labels
        self.transform = transform

    def __len__(self):
        return len(self.image_paths)

    def __getitem__(self, idx):
        image = Image.open(self.image_paths[idx]).convert('RGB')
        label = self.labels[idx]
        if self.transform:
            image = self.transform(image)
        return image, torch.tensor(label, dtype=torch.long)

# Transformações nas imagens
transform = transforms.Compose([
    transforms.Resize((224, 224)),
    transforms.ToTensor(),
])

# Criação dos DataLoaders
train_dataset = ScoliosisDataset(train_images, train_labels, transform=transform)
test_dataset = ScoliosisDataset(test_images, test_labels, transform=transform)

train_loader = DataLoader(train_dataset, batch_size=8, shuffle=True)
test_loader = DataLoader(test_dataset, batch_size=8, shuffle=False)

# Configuração do modelo (ResNet18)
device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
model = models.resnet18(pretrained=True)
model.fc = nn.Linear(model.fc.in_features, 2)  # 2 classes (normal/escoliose)
model = model.to(device)

# Definição da perda e do otimizador
criterion = nn.CrossEntropyLoss()
optimizer = optim.Adam(model.parameters(), lr=0.001)

# Loop de treinamento com mensagens de progresso
num_epochs = 15  # Ajuste conforme necessário
for epoch in range(num_epochs):
    model.train()
    running_loss = 0.0

    print(f'Epoch [{epoch+1}/{num_epochs}]')  # Mensagem do início da época

    for i, (images, labels) in enumerate(train_loader):
        images, labels = images.to(device), labels.to(device)

        # Forward pass
        outputs = model(images)
        loss = criterion(outputs, labels)

        # Backward pass e otimização
        optimizer.zero_grad()
        loss.backward()
        optimizer.step()

        running_loss += loss.item()

        # Exibir progresso a cada 10 lotes
        if (i + 1) % 10 == 0:
            print(f'  Batch [{i+1}/{len(train_loader)}], Loss: {loss.item():.4f}')

    # Exibir perda média da época
    avg_loss = running_loss / len(train_loader)
    print(f'Epoch [{epoch+1}/{num_epochs}] Loss: {avg_loss:.4f}')
    print('-' * 50)

# Avaliação no conjunto de teste com progresso
model.eval()
correct = 0
total = 0
print('Iniciando a avaliação no conjunto de teste...')
with torch.no_grad():
    for i, (images, labels) in enumerate(test_loader):
        images, labels = images.to(device), labels.to(device)
        outputs = model(images)
        _, predicted = torch.max(outputs.data, 1)
        total += labels.size(0)
        correct += (predicted == labels).sum().item()

        # Exibir progresso a cada 5 lotes
        if (i + 1) % 5 == 0:
            print(f'  Test Batch [{i+1}/{len(test_loader)}] processado.')

# Calcular e exibir a acurácia final
accuracy = 100 * correct / total
print(f'\nAccuracy on the test set: {accuracy:.2f}%')

